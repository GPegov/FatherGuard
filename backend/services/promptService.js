  static formatFullChronicle(entries) {
    if (!entries || entries.length === 0) {
      return "";
    }
    // Используем статический метод из ChronicleService через временный экземпляр
    // для доступа к методу formatDate, так как это наиболее централизованный способ
    return entries
      .map(entry => {
        // Создаем временный экземпляр ChronicleService с произвольным путем для вызова метода
        const tempChronicleService = new ChronicleService('');
        const date = tempChronicleService.formatDate(entry.date);
        return `${date} — ${entry.content}`;
      })
      .join('\n');
  }




  static buildDateContext(existingTimeline) {
    if (!existingTimeline.length) {
      return "Это первая запись в летописи.";
    }

    const recentEntries = existingTimeline
      .slice(0, 3)
      .map((entry) => `- ${entry.date}: ${entry.content.substring(0, 100)}...`)
      .join("\n");

    return `Последние записи в хронологическом порядке:\n${recentEntries}\n\nУчти эту последовательность событий при создании новой записи.`;
  }

  static getKeySentencesPrompt(text, sourceType) {
    const context =
      sourceType === "official_document"
        ? "официального документа (обрати внимание на юридические формулировки, решения, сроки)"
        : "пояснений пользователя (выдели фактические описания событий, даты, действия госорганов)";

    return `Извлеки 5 самых информативных предложений из ${context}:

ТЕКСТ:
${text.substring(0, Math.min(AIConfig.MAX_ANALYSIS_TEXT_LENGTH, 15000))}

Верни ТОЛЬКО массив JSON с предложениями, которые наиболее точно отражают суть:
["предложение 1", "предложение 2", "предложение 3", "предложение 4", "предложение 5"]`;
  }

